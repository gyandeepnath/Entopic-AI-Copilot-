#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════ */
/* SEED CLOUD KB                                                   */
/* Emits SQL that upserts the LOCAL knowledge base into the cloud    */
/* `public.kb_conditions` table (the authoring/growth platform) and  */
/* publishes a `kb_versions` bundle snapshot.                        */
/*                                                                  */
/* This does NOT hit the network — it prints SQL. Apply it with the  */
/* Supabase MCP (apply_migration) or `psql`. Kept out of the app;    */
/* the app never depends on the cloud KB at runtime.                 */
/*                                                                  */
/*   node tools/seed-cloud-kb.js            > kb_seed.sql            */
/*   node tools/seed-cloud-kb.js --version 1.0.0                     */
/* ═══════════════════════════════════════════════════════════════ */
"use strict";

const { loadKnowledgeBase } = require("./lib/load-kb");

const versionArg = (() => {
  const i = process.argv.indexOf("--version");
  return i >= 0 ? process.argv[i + 1] : null;
})();

function sqlStr(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}
function sqlJson(v) {
  return sqlStr(JSON.stringify(v || [])) + "::jsonb";
}
function sqlOrNull(v) {
  return v ? sqlStr(v) : "null";
}

function build() {
  const kb = loadKnowledgeBase();
  const ICD = kb.ICD_MAP || {};
  const ALL = kb.KNOWLEDGE_ALL;

  const rows = ALL.map((c) => {
    const icd = ICD[c.name] || {};
    const prov = {
      source: "entopic local KB",
      exported: new Date().toISOString().slice(0, 10),
      icd_verified: icd.verified || null,
      icd_caution: icd.caution || null
    };
    return "(" + [
      sqlStr(c.name), sqlStr(c._domain), sqlStr(c.route),
      sqlJson(c.req), sqlJson(c.sup), sqlJson(c.con),
      sqlJson(c.temporal), sqlJson(c.tests), sqlJson(c.exclusions),
      c.urgent ? "true" : "false",
      sqlOrNull(icd.icd10), sqlOrNull(icd.label),
      "'NEEDS_CLINICAL_REVIEW'", sqlJson(prov)
    ].join(",") + ")";
  });

  let sql = "-- Generated by tools/seed-cloud-kb.js — do not edit by hand.\n";
  sql += "insert into public.kb_conditions\n" +
    "  (name,domain,route,req,sup,con,temporal,tests,exclusions,urgent,icd10,icd_label,review_status,provenance)\n" +
    "values\n" + rows.join(",\n") + "\n" +
    "on conflict (name) do update set\n" +
    "  domain=excluded.domain, route=excluded.route, req=excluded.req, sup=excluded.sup,\n" +
    "  con=excluded.con, temporal=excluded.temporal, tests=excluded.tests,\n" +
    "  exclusions=excluded.exclusions, urgent=excluded.urgent, icd10=excluded.icd10,\n" +
    "  icd_label=excluded.icd_label, provenance=excluded.provenance, updated_at=now();\n";

  if (versionArg) {
    const bundle = buildBundle();
    sql += "\ninsert into public.kb_versions (version, notes, bundle, published)\n" +
      "values (" + sqlStr(versionArg) + ", 'seeded from local KB', " +
      sqlStr(JSON.stringify(bundle)) + "::jsonb, true)\n" +
      "on conflict (version) do update set bundle=excluded.bundle, published=true, notes=excluded.notes;\n";
  }

  return { sql, count: rows.length };
}

/* The exact bundle shape written to kb_versions.bundle — the same object the
   in-app remote-updater (js/kb-remote.js) downloads and validates. Exported
   so a test can prove the publish/consume contract without a network. */
function buildBundle() {
  const kb = loadKnowledgeBase();
  const bundle = {};
  for (const [domain, conds] of Object.entries(kb.KNOWLEDGE_DOMAINS)) {
    bundle[domain] = conds.map(({ _domain, _index, ...rest }) => rest);
  }
  return bundle;
}

if (require.main === module) {
  const { sql, count } = build();
  process.stdout.write(sql);
  process.stderr.write("\n-- " + count + " conditions" + (versionArg ? " + version " + versionArg : "") + "\n");
}

module.exports = { build, buildBundle };
